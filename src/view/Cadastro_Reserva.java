        private void CarregarDadosReserva() throws SQLException{
try {
    ApartamentoDAO aDAO = new ApartamentoDAO();
    List<Apartamento> apartamentos = aDAO.getApartamento();
    String[][] dados = new String[apartamentos.size()][4];
    for(int i = 0; i < apartamentos.size(); i++){
        dados[i][0] = String.valueOf(apartamentos.get(i).getId());
        dados[i][1] = apartamentos.get(i).getStatus();
        dados[i][2] = String.valueOf(apartamentos.get(i).getCapacidade());
        dados[i][3] = String.valueOf(apartamentos.get(i).getValorDiaria());

    String[] nomeColuna = {"Id","Status","Capacidade","ValorDiaria"};
    jTable1.setModel(new javax.swing.table.DefaultTableModel(dados,nomeColuna));
}
}catch (Exception ex) {
        JOptionPane.showMessageDialog(null, "Erro ao carregar a tabela: " + ex.getMessage());
    }
}
        
        private void CarregarDadosInquilino() throws SQLException{
try {
    InquilinoDAO iDAO = new InquilinoDAO();
    List<Inquilino> inquilinos = iDAO.getInquilino();
    String[][] dados = new String[inquilinos.size()][3];
    for(int i = 0; i < inquilinos.size(); i++){
        dados[i][0] = String.valueOf(inquilinos.get(i).getId());
        dados[i][1] = inquilinos.get(i).getNome();
        dados[i][2] = String.valueOf(inquilinos.get(i).getTelefone());
        

    String[] nomeColuna = {"InquilinoID","Nome","Telefone"};
    jTable2.setModel(new javax.swing.table.DefaultTableModel(dados,nomeColuna));
}
}catch (Exception ex) {
        JOptionPane.showMessageDialog(null, "Erro ao carregar a tabela: " + ex.getMessage());
    }
}
        

    private void jButton9ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton9ActionPerformed
String txtInquilino = inquilinotxt.getText().trim();
    String txtApto = apartamentotxt.getText().trim();
    String txtPagantes = pagantestxt.getText().trim();
    String txtCriancas = criancastxt.getText().trim();
    


int addInquilino = txtInquilino.isEmpty() ? 0 : Integer.parseInt(txtInquilino);
    int addApartamento = txtApto.isEmpty() ? 0 : Integer.parseInt(txtApto);
    int addPagantes = txtPagantes.isEmpty() ? 0 : Integer.parseInt(txtPagantes);
    int addCriancas = txtCriancas.isEmpty() ? 0 : Integer.parseInt(txtCriancas);
    String addCheckin = intxt.getText();
    String addCheckout = outtxt.getText();
    String addAr = artxt.getText();
    boolean arcond;


if (addInquilino == 0 || addApartamento == 0 || addCheckin.isEmpty() || addCheckout.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Inquilino, Quarto e Datas são obrigatórios!", "ERRO",JOptionPane.ERROR_MESSAGE);

} else {
    try {
 
        ReservaDAO rDao = new ReservaDAO(); 
        
        if(addAr.equalsIgnoreCase("sim")){
            arcond = true;
        }else{
            arcond = false;
        }
        Inquilino inovo = new Inquilino();
        
        Apartamento anovo = new Apartamento();
        anovo.setId(addApartamento);
        LocalDate datain = LocalDate.parse(addCheckin);
        LocalDate dataout = LocalDate.parse(addCheckout);
        InquilinoDAO iDao = new InquilinoDAO();
        inovo = iDao.buscarPorId(addInquilino);
        
        Reserva novar = new Reserva(0, datain, dataout, inovo, anovo,  arcond,0, addPagantes, addCriancas);
        
        rDao.cadastrar(novar); 

        JOptionPane.showMessageDialog(this, "Reserva cadastrada com sucesso!", "SUCESSO!", JOptionPane.INFORMATION_MESSAGE);
        this.LimparFormulario();
        

    } catch (Exception e) {
        if (e.getMessage().contains("Duplicate entry")) {
            JOptionPane.showMessageDialog(this, "Erro: Esta Reserva já está cadastrada!", "Atenção", JOptionPane.WARNING_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Erro no Banco: " + e.getMessage(), "ERRO", JOptionPane.ERROR_MESSAGE);
        }
    }
    }
        
        
        
        
        
        
        
    }//GEN-LAST:event_jButton9ActionPerformed

